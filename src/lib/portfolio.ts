export function slugProblem(raw: string): string | null {
  const slug = raw.trim();
  if (slug.length < 3 || slug.length > 30) return 'Your link name must be 3 to 30 characters.';
  if (!/^[a-z0-9-]+$/.test(slug)) return 'Use only lowercase letters, numbers and hyphens.';
  if (slug.startsWith('-') || slug.endsWith('-')) return 'Your link name can\u2019t start or end with a hyphen.';
  if (RESERVED.has(slug)) return 'That link name is reserved. Please choose another.';
  const flat = slug.replace(/-/g, '').replace(/0/g, 'o').replace(/1/g, 'i').replace(/3/g, 'e').replace(/4/g, 'a').replace(/5/g, 's').replace(/7/g, 't');
  if (OFFENSIVE.some((w) => flat.includes(w))) return 'That link name isn\u2019t allowed. Please choose another.';
  return null;
}

/** Plain text only: strips control characters and trims. Rendering is always as text, never HTML. */
export function cleanText(value: string | null | undefined, max: number): string {
  return (value ?? '').replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '').trim().slice(0, max);
}

/** Returns a normalised http(s) URL, or null when the link is empty. Throws for any other scheme. */
export function safeUrl(value: string | null | undefined): string | null {
  const v = (value ?? '').trim();
  if (!v) return null;
  let u: URL;
  try { u = new URL(v); } catch { throw new Error('Links must be full web addresses starting with https:// or http://'); }
  if (u.protocol !== 'https:' && u.protocol !== 'http:') throw new Error('Links must start with https:// or http://');
  if (v.length > 300) throw new Error('Links must be at most 300 characters.');
  return u.toString();
}
/** For display: only ever returns http(s) URLs; anything else is dropped. */
export function displayUrl(value: string | null | undefined): string | null {
  try { return safeUrl(value); } catch { return null; }
}

export type StageVisibility = { summary: boolean; replies: boolean; data: boolean };
export const DEFAULT_STAGE: StageVisibility = { summary: true, replies: true, data: false };
export function stageVisibility(settings: unknown, taskId: string): StageVisibility {
  const s = (settings && typeof settings === 'object' ? (settings as Record<string, Partial<StageVisibility>>)[taskId] : undefined) ?? {};
  return {
    summary: typeof s.summary === 'boolean' ? s.summary : DEFAULT_STAGE.summary,
    replies: typeof s.replies === 'boolean' ? s.replies : DEFAULT_STAGE.replies,
    data: typeof s.data === 'boolean' ? s.data : DEFAULT_STAGE.data,
  };
}

export type DataTable = { name: string; rows: Array<Record<string, string>> };
/** Collects the stage datasets (tables / datasets / dataset) into simple named tables, capped for display. */
export function stageTables(rubric: unknown, maxRows = 40): DataTable[] {
  if (!rubric || typeof rubric !== 'object') return [];
  const r = rubric as Record<string, unknown>;
  const raw: unknown[] = [];
  for (const k of ['tables', 'datasets', 'dataset']) {
    const v = r[k];
    if (Array.isArray(v)) raw.push(...v); else if (v && typeof v === 'object') raw.push(v);
  }
  return raw.flatMap((t, i) => {
    const o = t as { name?: unknown; rows?: unknown };
    if (!Array.isArray(o.rows)) return [];
    const rows = o.rows.slice(0, maxRows).filter((x) => x && typeof x === 'object').map((x) =>
      Object.fromEntries(Object.entries(x as Record<string, unknown>).map(([k, v]) => [k, v == null ? '' : String(v)])));
    return [{ name: typeof o.name === 'string' ? o.name : `Table ${i + 1}`, rows }];
  });
}

/** Question labels only (never answer keys) paired with the user's replies. */
export function stageReplies(rubric: unknown, response: unknown): Array<{ label: string; reply: string }> {
  const resp = (response && typeof response === 'object' ? response : {}) as Record<string, unknown>;
  const fields = (rubric && typeof rubric === 'object' && Array.isArray((rubric as { fields?: unknown }).fields)
    ? (rubric as { fields: Array<{ key?: unknown; label?: unknown }> }).fields : []);
  const out: Array<{ label: string; reply: string }> = [];
  const seen = new Set<string>();
  for (const f of fields) {
    if (typeof f.key !== 'string') continue;
    seen.add(f.key);
    const v = resp[f.key];
    if (v == null || v === '') continue;
    out.push({ label: typeof f.label === 'string' ? f.label : f.key, reply: cleanText(typeof v === 'string' ? v : JSON.stringify(v), 4000) });
  }
  for (const [k, v] of Object.entries(resp)) {
    if (seen.has(k) || v == null || v === '') continue;
    const label = typeof (rubric as { prompt_label?: unknown })?.prompt_label === 'string' ? (rubric as { prompt_label: string }).prompt_label : 'Your answer';
    out.push({ label: k === 'a' || k === 'answer' ? label : k.replace(/_/g, ' '), reply: cleanText(typeof v === 'string' ? v : JSON.stringify(v), 4000) });
  }
  return out;
}

export function ctaCopy(s: { enforced: boolean; launchFreeUntil: string | null; trialDays: number }, now = Date.now()) {
  const base = 'Build your own verified portfolio. Practice real job simulations and show your skills.';
  if (!s.enforced) {
    const until = s.launchFreeUntil ? new Date(`${s.launchFreeUntil}T23:59:59Z`).getTime() : 0;
    return { body: base, note: until > now ? 'Free during launch.' : null, button: 'Create your portfolio' };
  }
  return { body: base, note: null, button: s.trialDays > 0 ? 'Start your free trial' : 'Create your portfolio' };
}

